import { afterEach, expect, it, vi } from 'vitest';
import { randomUUID } from 'node:crypto';
import { SessionRegistry, resolvePending } from '@mitzo/harness';
import { CredentialResolver } from '../credentials.js';
import { PublicationCredentialCustodian } from '../symposium-publication-credentials.js';
import { GithubMainPublication } from '../github-main-publication.js';
import { TelosMainPublication, type MainPublicationHost } from '../telos-main-publication.js';
import { approveGithubMainPublication } from '../github-main-publication-permission.js';
import {
  fixture as github,
  pins as originalPins,
  config,
  merge,
} from './fixtures/github-main-publication.js';
import { createTelosCanonicalData } from './fixtures/telos-canonical-advisor.js';

const external = vi.hoisted(() => ({
  execute: undefined as
    | undefined
    | ((command: string, args: readonly string[]) => Promise<{ stdout: string; stderr: string }>),
}));
vi.mock('node:child_process', () => ({
  execFile: Object.assign(
    () => {
      throw Error('Only promisified external execution is expected');
    },
    {
      [Symbol.for('nodejs.util.promisify.custom')]: (command: string, args: readonly string[]) => {
        if (!external.execute) throw Error('External fixture is not installed');
        return external.execute(command, args);
      },
    },
  ),
}));
afterEach(() => {
  external.execute = undefined;
});

// The original custodian/default isolated runner, S6 adapter, one-use permission,
// WorkStore/control checks and append-only ACK ledger are real. Only the external
// credential/GitHub process and operator transport edges are controlled. The host
// tuple is a component port; this does not qualify native caller installation.
it.each(['credential-disconnect', 'native-abort'] as const)(
  'persists the real adapter ACK after %s and retains uncertainty without another effect',
  async (change) => {
    const data = createTelosCanonicalData();
    const registry = new SessionRegistry();
    try {
      const command = (operation: object) =>
        data.work.execute(
          {
            requestId: randomUUID(),
            itemId: 'studio',
            expectedRevision: data.work.read('studio', data.actor).revision,
            ...operation,
          },
          data.actor,
        );
      command({ operation: 'classify', kind: 'outcome' });
      command({
        operation: 'link',
        role: 'lead',
        conversation: { namespace: 'mitzo', conversationId: 'planning' },
      });
      command({
        operation: 'assign',
        role: 'lead',
        conversationId: 'planning',
        expectedAssignmentRevision: 0,
      });
      const pins = structuredClone(originalPins);
      pins.input = {
        ...pins.input,
        requestId: randomUUID(),
        itemId: 'studio',
        workRevision: data.work.read('studio', data.actor).revision,
      };
      pins.authority = {
        ...pins.authority,
        operatorId: data.actor.id,
        conversationId: 'planning',
        assignmentRevision: 1,
      };
      const remote = github(pins);
      const credentials = new PublicationCredentialCustodian(
        new CredentialResolver({
          test: { resolve: async () => 'synthetic-selected-merge-credential' },
        }),
      );
      credentials.register(config.connectionId, 'Explicit component connection', {
        provider: 'test',
        service: 'github',
        account: 'merge-operator',
      });
      const handle = await credentials.select(config.connectionId, 1);
      const native = new AbortController();
      let permissions = 0;
      registry.register('client', {
        sessionId: 'planning',
        mode: 'agent',
        sessionAllowList: new Set(),
        abortController: new AbortController(),
        transport: {
          isOpen: () => true,
          send: (event) => {
            if (event.type !== 'permission_request') return;
            if (typeof event.permId !== 'string') throw Error('Original permission ID unavailable');
            const permissionId = event.permId;
            permissions++;
            queueMicrotask(() => resolvePending(permissionId, 'once', undefined, 'planning'));
          },
        },
      });
      external.execute = async (program, args) => {
        // The external process actually succeeds with this response. Its stdout
        // is never inferred from a rejection or generated by the ACK callback.
        const response = await remote.run(program, args);
        if (args.some((arg) => arg.includes('mergePullRequest('))) {
          if (change === 'native-abort') native.abort();
          else credentials.disconnect(handle.connectionId, handle.revision);
        }
        return response;
      };
      const capability = new GithubMainPublication(
        config,
        async (program, args, signal) => {
          if (program !== 'gh') throw Error('Unexpected GitHub command');
          return {
            ...(await handle.run(program, args, AbortSignal.any([signal, native.signal]))),
            stderr: '',
          };
        },
        async (_program, args, signal, admit) => ({
          ...(await credentials.dispatchMainMerge(
            handle,
            args,
            AbortSignal.any([signal, native.signal]),
            admit,
          )),
          stderr: '',
        }),
      );
      const assertCurrent = () => {
        native.signal.throwIfAborted();
        handle.assertCurrent();
        data.work.mainPublicationsForHost().assertWorkCurrent(pins);
      };
      const host: MainPublicationHost = {
        resolve: async () => ({ authority: pins.authority, capability }),
        assertCurrent,
        approve: (presentation, signal) =>
          approveGithubMainPublication(registry, 'client', presentation, signal, assertCurrent),
      };
      const owner = new TelosMainPublication(data.work, host);
      const result = await owner.request(pins.input, native.signal);
      expect(result.state).toBe('uncertain');
      expect(permissions).toBe(1);
      expect(remote.state.mutations).toBe(1);
      const rows = data.db
        .prepare(
          'SELECT merge_commit,approval_receipt_id FROM telos_work_main_publication_acknowledgements',
        )
        .all();
      expect(rows).toEqual([{ merge_commit: merge, approval_receipt_id: expect.any(String) }]);
      await expect(capability.inspect(pins, new AbortController().signal)).rejects.toThrow();
      expect((await owner.request(pins.input, new AbortController().signal)).state).toBe(
        'uncertain',
      );
      expect(remote.state.mutations).toBe(1);
      expect(permissions).toBe(1);
      expect(
        data.db
          .prepare(
            'SELECT merge_commit,approval_receipt_id FROM telos_work_main_publication_acknowledgements',
          )
          .all(),
      ).toEqual(rows);
    } finally {
      registry.dispose();
      data.close();
    }
  },
);
